def build():
    bundle = {
        "schema_version": "0.2",
        "project": {
            "project_id": "DEMO-P02",
            "research_question": "如何为工作日备餐的两人家庭优化冰箱内布局？",
            "question_version": "1",
        },
        "themes": [{"theme_id": theme_id, "label": label, "definition": definition}
                   for theme_id, label, definition in themes],
        "sessions": [], "excerpts": [], "observations": [], "insights": [],
    }
    for session_number, (context, answers) in enumerate(sessions, 1):
        session_id = f"DEMO-S{session_number:02d}"
        filename = f"S{session_number:02d}_扩展模拟访谈.txt"
        lines = []
        for answer_number, row in enumerate(answers, 1):
            question, quote, task, action, obstacle, consequence, workaround, unknown, *rest = row
            evidence_type = rest[0] if rest else SELF
            number = (session_number - 1) * 4 + answer_number
            excerpt_id = f"DEMO-E{number:02d}"
            lines.extend([f"访谈员：{question}", f"受访者：{quote}"])
            bundle["excerpts"].append({
                "excerpt_id": excerpt_id, "session_id": session_id,
                "line_start": answer_number * 2, "line_end": answer_number * 2,
                "speaker": "受访者", "quote": quote, "preceding_question": question,
            })
            bundle["observations"].append({
                "observation_id": f"DEMO-O{number:02d}", "excerpt_ids": [excerpt_id],
                "evidence_type": evidence_type, "task": task, "action": action,
                "object": "", "context": context, "obstacle": obstacle,
                "consequence": consequence, "workaround": workaround, "unknown": unknown,
            })
        (HERE / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")
        bundle["sessions"].append({
            "session_id": session_id, "participant_code": f"模拟U{session_number:02d}",
            "date": f"2026-09-{18 + session_number:02d}", "method": "虚构访谈",
            "context": context + "；内容完全虚构", "source_file": filename,
            "source_url": "", "transcript_version": "1",
            "use_scope": "仅作界面试验；非真实研究证据",
        })
    for number, spec in enumerate(insight_specs, 1):
        theme_id, statement, applies_to, supports, limits, alternatives, questions = spec
        bundle["insights"].append({
            "insight_id": f"DEMO-I{number:02d}", "theme_id": theme_id, "statement": statement,
            "applies_to": applies_to,
            "support_observation_ids": [f"DEMO-O{item:02d}" for item in supports],
            "limiting_observation_ids": [f"DEMO-O{item:02d}" for item in limits],
            "alternative_explanations": alternatives, "open_questions": questions,
            "status": "待审", "reviewer": "", "review_reason": "",
        })
    (HERE / "模拟数据_bundle.json").write_text(
        json.dumps(bundle, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"生成 {len(bundle['sessions'])} 份访谈、{len(bundle['excerpts'])} 段原话、"
          f"{len(bundle['observations'])} 条观察、{len(bundle['insights'])} 张候选洞察")


if __name__ == "__main__":
    build()
